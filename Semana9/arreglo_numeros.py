# Crear un arreglo con los números 10, 20, 30, 40 y 50

numeros = [10, 20, 30, 40, 50]
 
# Seleccionar la posición 1 del arreglo

posicion = 1
 
# Mostrar el número almacenado en la posición 1

print("Número en la posición 1:", numeros[posicion])
 
# Recorrer todos los elementos del arreglo desde la primera posición

for i in range(len(numeros)):
 
    # Mostrar cada número en pantalla

    print("Elemento:", numeros[i])